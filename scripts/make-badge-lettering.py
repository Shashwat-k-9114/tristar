"""
Pre-computes the badge lettering as outlined glyph paths (one combined <path> per line of text).

Why: live SVG <text><textPath> was the single most expensive item in mobile layout (about 0.45 s of the 4x-CPU
hero LCP in A/B probes). The badges are decorative (aria-hidden; the same words are real text in the page headings),
so outlines lose nothing and render as cheap paths.

Fonts are SIL OFL 1.1 (outlining is permitted): Fraunces SemiBold (names) and Hind Medium (ribbons). Run against the
woff2 files of a finished `next build`:

    pip install fonttools brotli
    python scripts/make-badge-lettering.py <fraunces.woff2> <hind.woff2>

Writes src/components/brand/lettering.ts (UTF-8).
"""
import math
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

fraunces = TTFont(sys.argv[1])
hind = TTFont(sys.argv[2])


def glyph_run(font, text, size, tracking_em):
    gs = font.getGlyphSet()
    cmap = font.getBestCmap()
    upm = font["head"].unitsPerEm
    sc = size / upm
    items = []
    for ch in text:
        name = cmap.get(ord(ch))
        if name is None:
            raise SystemExit(f"glyph missing for {ch!r}")
        adv = font["hmtx"][name][0] * sc
        items.append((name, adv))
    track = tracking_em * size
    total = sum(a for _, a in items) + track * (len(items) - 1)
    return gs, sc, items, track, total


def place(font, text, size, tracking_em, point_at, path_len):
    """point_at(s) -> (x, y, rotation_radians) along the guide at arc length s. Returns one SVG path string."""
    gs, sc, items, track, total = glyph_run(font, text, size, tracking_em)
    pen = SVGPathPen(gs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
    s = (path_len - total) / 2
    for name, adv in items:
        x, y, rot = point_at(s + adv / 2)
        c, si = math.cos(rot), math.sin(rot)
        # glyph space (font units, y up) -> centred on its advance, baseline at 0, flipped to SVG y-down, rotated, translated
        # local = (gx*sc - adv/2, -gy*sc)
        a, b = c * sc, si * sc  # x basis
        cc, d = -si * -sc, c * -sc  # y basis (y flipped)
        # rotation matrix applied to (lx, ly): (c*lx - si*ly, si*lx + c*ly)
        e = x - (c * adv / 2)
        f = y - (si * adv / 2)
        tp = TransformPen(pen, (a, b, cc, d, e, f))
        gs[name].draw(tp)
        s += adv + track
    return pen.getCommands()


# top arc: circle r about (200,200), from the left point clockwise over the top
def arc_top(r):
    L = math.pi * r

    def at(s):
        th = math.pi + s / r
        return 200 + r * math.cos(th), 200 + r * math.sin(th), th + math.pi / 2

    return at, L


# ribbon: quadratic bezier M64 301 Q200 331 336 301
def ribbon():
    p0, p1, p2 = (64, 301), (200, 331), (336, 301)
    n = 400
    pts = []
    for i in range(n + 1):
        t = i / n
        x = (1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t**2 * p2[0]
        y = (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t**2 * p2[1]
        pts.append((x, y))
    cum = [0.0]
    for i in range(1, len(pts)):
        cum.append(cum[-1] + math.dist(pts[i], pts[i - 1]))
    L = cum[-1]

    def at(s):
        s = max(0, min(L, s))
        i = next(k for k in range(1, len(cum)) if cum[k] >= s)
        seg = cum[i] - cum[i - 1]
        u = (s - cum[i - 1]) / seg if seg else 0
        x = pts[i - 1][0] + (pts[i][0] - pts[i - 1][0]) * u
        y = pts[i - 1][1] + (pts[i][1] - pts[i - 1][1]) * u
        rot = math.atan2(pts[i][1] - pts[i - 1][1], pts[i][0] - pts[i - 1][0])
        return x, y, rot

    return at, L


names = {"tristar": ("TRISTAR", 34), "biryani": ("BIRYANI", 36), "samosa": ("SAMOSA", 36), "thali": ("THALI", 40)}
ribbons = {"tristar": "BIRYANI · SAMOSA · THALI", "biryani": "CHICKEN BIRYANI", "samosa": "MUTTON · VEGETABLE", "thali": "A COMPLETE MEAL"}

out = ["// GENERATED by scripts/make-badge-lettering.py — do not edit. Outlined Fraunces SemiBold / Hind Medium (SIL OFL 1.1).", "export const lettering: Record<string, string> = {"]
for k, (text, size) in names.items():
    at, L = arc_top(110)
    out.append(f'  "{k}-name": "{place(fraunces, text, size, 0.08, at, L)}",')
for k, text in ribbons.items():
    at, L = ribbon()
    out.append(f'  "{k}-ribbon": "{place(hind, text, 17, 0.14, at, L)}",')
out.append("};")
Path("src/components/brand/lettering.ts").write_text("\n".join(out) + "\n", encoding="utf-8")
print("ok", sum(len(x) for x in out), "chars")
